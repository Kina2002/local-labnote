import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const context={};vm.createContext(context);vm.runInContext(fs.readFileSync(new URL('../web/editor.js',import.meta.url),'utf8'),context);
const apply=(value,edit)=>edit?value.slice(0,edit.start)+edit.text+value.slice(edit.end):value;
const format=(value,action,start=0,end=value.length)=>apply(value,context.formatNoteLines(value,start,end,action));
const enter=(value,start=value.length,end=start)=>apply(value,context.continueNoteLine(value,start,end));
assert.equal(format('시약 A\n시약 B','bullet'),'• 시약 A\n• 시약 B');
assert.equal(format('• 시약 A\n• 시약 B','bullet'),'시약 A\n시약 B');
assert.equal(format('• 준비\n• 측정','number'),'1. 준비\n2. 측정');
assert.equal(format('  • 혼합\n  • 건조','indent'),'    • 혼합\n    • 건조');
assert.equal(format('  • 혼합\n  • 건조','outdent'),'• 혼합\n• 건조');
assert.equal(format('첫째\n둘째','bullet',0,3),'• 첫째\n둘째');
assert.equal(format('\n둘째','bullet',0,0),'• \n둘째');
assert.equal(enter('  • 관찰'),'  • 관찰\n  • ');
assert.equal(enter('9. 측정'),'9. 측정\n10. ');
assert.equal(enter('  2) 측정'),'  2) 측정\n  3) ');
assert.equal(enter('• '),'');
assert.equal(enter('  2. '),'');
assert.equal(enter('    메모'),'    메모\n    ');
assert.equal(enter('• 가나다',4),'• 가나\n• 다');
assert.equal(context.continueNoteLine('일반 문장',5,5),null);
assert.equal(format('앞\n• 뒤','bullet',3,5),'앞\n뒤');
console.log('Passed 16 editor checks: lists, numbering, selection boundaries, indent/outdent, empty items, mid-line Enter and plain text.');
